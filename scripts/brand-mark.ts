// Draws the brand mark, an impossible triangle built from cubes (Reutersvärd's
// figure, the one Penrose later drew as a tribar), into public/logo.svg,
// favicon.svg and og.svg. Run `bun run brand:mark`, then rasterize
// og.svg to og.png as the comment in that file says. All three are generated:
// change the numbers here, not the files.
//
// The figure is not drawn freehand. Cubes are laid along +x, +y, then +z, STEPS
// at a time, and seen in isometric projection, where (1, 1, 1) projects to
// nothing: the walk ends at (STEPS, STEPS, STEPS), which lands exactly on the
// first cube. So the loop closes on paper and nowhere else.
//
// Painting it takes two rules. A face against another cube is never drawn —
// including the last cube's top, which the first cube covers on paper. That
// leaves one pair of cubes overlapping without touching: the first cube along
// x, and the last cube along z. Drawing the x cube over the z one is what makes
// the corner read as a corner; every other order is back to front.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { SITE_NAME } from '../src/site';

const PRIMARY = '#5200ff';
/** The dark theme's accent: PRIMARY mixed 1:1 with white. */
const TINT = '#a980ff';
const STEPS = 4; // cubes per side, less the shared corner
const GAP = 0.06; // of each face, left open between faces

type V3 = [number, number, number];
type Pt = [number, number];

/** The three visible faces, as the light catches them. */
interface Tones {
  top: string;
  left: string; // the +y face
  right: string; // the +x face
}

const C30 = Math.cos(Math.PI / 6);
const project = ([x, y, z]: V3): Pt => [(x - y) * C30, (x + y) / 2 - z];

const cubes: V3[] = Array.from(
  { length: 3 * STEPS },
  (_, k): V3 =>
    k < STEPS ? [k, 0, 0] : k < 2 * STEPS ? [STEPS, k - STEPS, 0] : [STEPS, STEPS, k - 2 * STEPS],
);
const occupied = new Set([...cubes, [STEPS, STEPS, STEPS] as V3].map((c) => c.join()));

/** The mark as <path> elements, fitted and centred in the square at (x, y).
 *  `paint` turns a tone into the attribute that colours a face. */
function markPaths(
  x: number,
  y: number,
  size: number,
  tones: Tones,
  paint = (tone: string) => `fill="${tone}"`,
): string {
  const faces = cubes.flatMap(([i, j, k], index) => {
    // The first cube along x goes over the last one along z: see the header.
    const order = index === 1 ? cubes.length : index;
    const sides: [V3, V3[], string][] = [
      [
        [i, j, k + 1],
        [
          [i, j, k + 1],
          [i + 1, j, k + 1],
          [i + 1, j + 1, k + 1],
          [i, j + 1, k + 1],
        ],
        tones.top,
      ],
      [
        [i + 1, j, k],
        [
          [i + 1, j, k],
          [i + 1, j + 1, k],
          [i + 1, j + 1, k + 1],
          [i + 1, j, k + 1],
        ],
        tones.right,
      ],
      [
        [i, j + 1, k],
        [
          [i, j + 1, k],
          [i + 1, j + 1, k],
          [i + 1, j + 1, k + 1],
          [i, j + 1, k + 1],
        ],
        tones.left,
      ],
    ];
    return sides
      .filter(([neighbour]) => !occupied.has(neighbour.join()))
      .map(([, corners, fill]) => ({ order, fill, points: corners.map(project) }));
  });
  faces.sort((a, b) => a.order - b.order);

  const all = faces.flatMap((f) => f.points);
  const [minX, maxX] = [Math.min(...all.map((p) => p[0])), Math.max(...all.map((p) => p[0]))];
  const [minY, maxY] = [Math.min(...all.map((p) => p[1])), Math.max(...all.map((p) => p[1]))];
  const scale = size / Math.max(maxX - minX, maxY - minY);
  const place = ([px, py]: Pt): string =>
    `${+(x + size / 2 + (px - (minX + maxX) / 2) * scale).toFixed(2)} ${+(y + size / 2 + (py - (minY + maxY) / 2) * scale).toFixed(2)}`;
  return faces
    .map(({ fill, points }) => {
      const [cx, cy] = [
        points.reduce((s, p) => s + p[0], 0) / 4,
        points.reduce((s, p) => s + p[1], 0) / 4,
      ];
      const shrunk = points.map(
        ([px, py]): Pt => [cx + (px - cx) * (1 - GAP), cy + (py - cy) * (1 - GAP)],
      );
      return `<path ${paint(fill)} d="M${shrunk.map(place).join('L')}Z"/>`;
    })
    .join('\n  ');
}

/** The mark in the brand violet, for light grounds. */
const VIOLET: Tones = { top: TINT, left: PRIMARY, right: '#3500a6' };
/** On a dark or violet ground the mark turns to light: white tops, lavender
 *  and tint sides. #5200ff itself is ~2.6:1 on near-black. */
const LIGHT: Tones = { top: '#ffffff', left: '#dcccff', right: TINT };
const css = (t: Tones) => `.t{fill:${t.top}}.l{fill:${t.left}}.r{fill:${t.right}}`;

const logo = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="${SITE_NAME}">
  <!-- Generated by scripts/brand-mark.ts. The mark itself, in the brand
       violet, for light grounds; favicon.svg shows the tones for dark ones. -->
  ${markPaths(2, 2, 60, VIOLET)}
</svg>
`;

const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="${SITE_NAME}">
  <!-- Generated by scripts/brand-mark.ts. The mark with no tile behind it:
       violet on a light tab bar, light tones on a dark one, where ${PRIMARY}
       itself would be ~2.6:1. -->
  <style>${css(VIOLET)}@media (prefers-color-scheme:dark){${css(LIGHT)}}</style>
  ${markPaths(2, 2, 60, { top: 't', left: 'l', right: 'r' }, (tone) => `class="${tone}"`)}
</svg>
`;

const og = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630" width="1200" height="630" role="img" aria-label="${SITE_NAME}">
  <!-- Generated by scripts/brand-mark.ts. Source for public/og.png, the
       default Open Graph card. Browsers do not accept SVG for og:image, so the
       PNG beside this file is what ships: rasterize this file to
       public/og.png with sips on macOS, or any SVG rasterizer elsewhere. -->
  <rect width="1200" height="630" fill="${PRIMARY}" />
  ${markPaths(470, 64, 260, LIGHT)}
  <text x="600" y="462" text-anchor="middle" font-family="Helvetica Neue, Helvetica, Arial, sans-serif" font-size="88" fill="#ffffff">${SITE_NAME}</text>
</svg>
`;

for (const [file, svg] of [
  ['logo.svg', logo],
  ['favicon.svg', favicon],
  ['og.svg', og],
] as const) {
  writeFileSync(resolve(process.cwd(), 'public', file), svg);
  console.log(`public/${file}: ${svg.length} bytes`);
}
